-- AI Trading Arena: full database schema.
-- How to apply: Supabase dashboard -> SQL Editor -> New query -> paste this whole file -> Run.
-- Safe to run again: everything uses IF NOT EXISTS / DROP ... IF EXISTS.
--
-- Security model:
--   * Row Level Security is ON for every table.
--   * The dashboard uses the public "anon" key: it may only SELECT display tables.
--   * Only the pipeline writes, using the secret service_role key (bypasses RLS), stored in GitHub Secrets.
--   * prices_daily is NOT readable by anon: Tiingo's free terms don't allow redistributing raw prices.

-- ---------- Market data ----------
create table if not exists stocks (
  ticker      text primary key,
  name        text not null,
  sector      text,
  active      boolean not null default true,
  updated_at  timestamptz not null default now()
);

create table if not exists prices_daily (
  ticker     text not null references stocks(ticker),
  date       date not null,
  open       double precision,
  high       double precision,
  low        double precision,
  close      double precision,
  adj_close  double precision,
  volume     bigint,
  primary key (ticker, date)
);

-- ---------- Information ----------
create table if not exists sources (
  id                bigint generated by default as identity primary key,
  name              text not null,
  domain            text not null unique,
  trust_alpha       double precision not null default 1,
  trust_beta        double precision not null default 1,
  trust_score       double precision not null default 0.5,
  claims_evaluated  integer not null default 0,
  created_at        timestamptz not null default now()
);

create table if not exists articles (
  id            bigint generated by default as identity primary key,
  source_id     bigint not null references sources(id),
  url           text not null unique,
  kind          text not null default 'news' check (kind in ('news', 'filing')),
  feed          text,
  title         text not null,
  snippet       text,
  published_at  timestamptz not null,   -- used by the no-look-ahead rule
  collected_at  timestamptz not null default now(),
  tickers       text[] not null default '{}'
);
create index if not exists articles_published_at_idx on articles (published_at);
create index if not exists articles_tickers_idx on articles using gin (tickers);

create table if not exists fact_cards (
  id            bigint generated by default as identity primary key,
  article_id    bigint not null references articles(id),
  ticker        text references stocks(ticker),
  claim         text not null,
  direction     text not null check (direction in ('positive', 'negative', 'neutral')),
  claim_type    text not null check (claim_type in ('earnings', 'guidance', 'product', 'legal', 'macro', 'rumor', 'other')),
  horizon_days  integer not null,
  confidence    double precision check (confidence between 0 and 1),
  corroborated  boolean not null default false,
  created_at    timestamptz not null default now()
);

-- Every source that made a (deduplicated) claim.
create table if not exists fact_card_sources (
  fact_card_id  bigint not null references fact_cards(id),
  article_id    bigint not null references articles(id),
  source_id     bigint not null references sources(id),
  primary key (fact_card_id, article_id)
);

create table if not exists claim_evaluations (
  id             bigint generated by default as identity primary key,
  fact_card_id   bigint not null unique references fact_cards(id),
  evaluated_at   timestamptz not null default now(),
  excess_return  double precision,
  outcome        text not null check (outcome in ('correct', 'incorrect', 'unclear'))
);

-- ---------- Teams and trading ----------
create table if not exists teams (
  id              bigint generated by default as identity primary key,
  name            text not null,
  generation      integer not null default 0,
  parent_team_id  bigint references teams(id),
  mutation        text,
  config          jsonb not null default '{}',
  status          text not null default 'active' check (status in ('active', 'retired')),
  created_at      timestamptz not null default now(),
  retired_at      timestamptz
);

create table if not exists portfolios (
  team_id      bigint primary key references teams(id),
  cash         double precision not null,
  peak_equity  double precision,
  updated_at   timestamptz not null default now()
);

create table if not exists positions (
  team_id    bigint not null references teams(id),
  ticker     text not null references stocks(ticker),
  shares     integer not null check (shares > 0),
  avg_cost   double precision not null,
  opened_at  date not null,
  primary key (team_id, ticker)
);

create table if not exists runs (
  id           bigint generated by default as identity primary key,
  run_date     date not null,
  started_at   timestamptz not null default now(),
  finished_at  timestamptz,
  status       text not null default 'running' check (status in ('running', 'ok', 'partial', 'failed', 'skipped')),
  dry_run      boolean not null default false,
  error        text,
  summary      jsonb not null default '{}'
);

create table if not exists decisions (
  id              bigint generated by default as identity primary key,
  run_id          bigint references runs(id),
  team_id         bigint not null references teams(id),
  date            date not null,
  ticker          text references stocks(ticker),
  analyst_report  text,
  bull_case       text,
  bear_case       text,
  judge_verdict   jsonb,
  lessons_used    bigint[] not null default '{}',
  risk_result     jsonb,
  final_action    text,
  created_at      timestamptz not null default now()
);

create table if not exists orders (
  id           bigint generated by default as identity primary key,
  team_id      bigint not null references teams(id),
  decision_id  bigint references decisions(id),
  ticker       text not null references stocks(ticker),
  side         text not null check (side in ('buy', 'sell')),
  shares       integer not null check (shares > 0),
  status       text not null default 'pending' check (status in ('pending', 'filled', 'cancelled', 'rejected')),
  reason       text,
  for_date     date not null,
  created_at   timestamptz not null default now()
);

create table if not exists trades (
  id           bigint generated by default as identity primary key,
  order_id     bigint unique references orders(id),
  team_id      bigint not null references teams(id),
  ticker       text not null references stocks(ticker),
  side         text not null check (side in ('buy', 'sell')),
  shares       integer not null,
  fill_price   double precision not null,
  fees         double precision not null default 0,
  slippage     double precision not null default 0,
  executed_at  date not null
);

create table if not exists closed_trades (
  id                 bigint generated by default as identity primary key,
  team_id            bigint not null references teams(id),
  ticker             text not null references stocks(ticker),
  shares             integer not null,
  entry_date         date not null,
  entry_price        double precision not null,
  exit_date          date not null,
  exit_price         double precision not null,
  pnl                double precision not null,
  pnl_pct            double precision not null,
  holding_days       integer not null,
  benchmark_return   double precision,
  entry_decision_id  bigint references decisions(id),
  exit_decision_id   bigint references decisions(id)
);

-- ---------- Learning ----------
create table if not exists post_mortems (
  id                bigint generated by default as identity primary key,
  closed_trade_id   bigint not null unique references closed_trades(id),
  team_id           bigint not null references teams(id),
  what_happened     text,
  right_or_wrong    text,
  what_was_missed   text,
  lesson_candidate  text,
  created_at        timestamptz not null default now()
);

create table if not exists lessons (
  id              bigint generated by default as identity primary key,
  team_id         bigint references teams(id),   -- null = shared lesson book
  text            text not null,
  post_mortem_id  bigint references post_mortems(id),
  times_used      integer not null default 0,
  times_helpful   integer not null default 0,
  score           double precision not null default 0.5,
  active          boolean not null default true,
  created_at      timestamptz not null default now()
);

-- ---------- Performance and costs ----------
create table if not exists equity_daily (
  team_id          bigint not null references teams(id),
  date             date not null,
  cash             double precision not null,
  positions_value  double precision not null,
  total_equity     double precision not null,
  primary key (team_id, date)
);

create table if not exists benchmark_daily (
  date    date primary key,
  equity  double precision not null
);

create table if not exists llm_usage (
  id             bigint generated by default as identity primary key,
  run_id         bigint references runs(id),
  provider       text not null,
  model          text not null,
  role           text not null,
  input_tokens   integer not null default 0,
  output_tokens  integer not null default 0,
  cost_usd       double precision not null default 0,
  created_at     timestamptz not null default now()
);

